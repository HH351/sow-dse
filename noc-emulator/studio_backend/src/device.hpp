#pragma once
#include <array>
#include <cstdint>
#include <cstdlib>
#include <memory>
#include <span>
#include <stdexcept>
#include <string>
#include <vector>

namespace noc {
enum Code { Timeout = 1, Busy, BadConfig, Capacity, NoMemory, IoError, FpgaError };
struct Error : std::runtime_error {
    int32_t code;
    Error(Code c, const std::string &message) : runtime_error(message), code(c) {}
};
enum Transform { Transpose = 1, FlipRows = 2, FlipCols = 4 };
struct Mesh {
    uint32_t rows, cols, origin_row, origin_col, transform, routing;
};
struct Event {
    uint64_t send_time;
    uint32_t flit_num;
    uint8_t src, dst, mid;
};
struct Link { uint16_t src, dst, physical_id; uint8_t kind; };
struct Counters { uint64_t flits, heads, blocked, contended; };
struct Timings {
    uint64_t prepare_ns, upload_ns, command_to_done_ns, download_ns, decode_ns, submit_to_result_ns;
};
struct Result {
    std::vector<uint64_t> completion_cycles;
    std::array<Counters, 352> physical_counters{};
    uint64_t logical_cycle = 0;
    Timings timings{};
};

// Internal synchronous transport. Mesh/events are validated/generated by the
// Studio backend; each source's events already have nondecreasing send times.
class Device {
public:
    explicit Device(const Mesh &mesh);
    Result run(std::span<const Event> events);
    const std::vector<Link> &links() const { return links_; }
private:
    struct Fd {
        int value = -1;
        Fd() = default;
        ~Fd();
        Fd(const Fd &) = delete;
        Fd &operator=(const Fd &) = delete;
    } h2c_, c2h_;
    std::unique_ptr<void, decltype(&std::free)> scratch_{nullptr, &std::free};
    std::array<uint8_t, 64> map_{};
    std::vector<Link> links_;
    uint32_t routing_;
    void dma(bool write, uint64_t address, void *data, size_t bytes);
};
} // namespace noc
